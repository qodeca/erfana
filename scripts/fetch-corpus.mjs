// Fetches the pinned extra sources of the comment corpus round trip (spec 024,
// 024-NFR-003: "a pinned manifest … and a fetch script into a git-ignored cache").
//
// The repository's own files and the installed packages give about 150 HTML files;
// 024-AC-026 needs 500. Each source below is a released archive with a permissive
// licence, downloaded once into the git-ignored `temp/corpus/sources/<label>/`,
// checked against its SHA-256 before it is unpacked. `roots.json` there lists what
// was fetched; the collect step reads it when `CORPUS_EXTRA_ROOTS` is unset, so
// `npm run test:corpus` gives the same corpus on every machine.
//
//   node scripts/fetch-corpus.mjs           fetch what is missing (no network when all are present)
//   node scripts/fetch-corpus.mjs --force   fetch every source again
//
// To bump a source: change `url` and `dir`, then `sha256` to the new archive's hash.

import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { Buffer } from 'node:buffer'
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const SOURCES_DIR = join(ROOT, 'temp', 'corpus', 'sources')

export const SOURCES = [
  {
    // Python's documentation as HTML: 579 HTML files, generated by Sphinx.
    label: 'python-3.14.9-docs',
    licence: 'PSF-2.0',
    url: 'https://www.python.org/ftp/python/doc/3.14.9/python-3.14.9-docs-html.tar.bz2',
    sha256: '69bfb2e60d30a017a86ac0bb978243f0e0b15e46981f0107d0cc8ce1c9042a1c',
    /** The folder inside the archive that holds the files. */
    dir: 'python-3.14.9-docs-html'
  }
]

function fail(message) {
  console.error(`fetch-corpus: ${message}`)
  process.exit(2)
}

async function fetchSource(source, force) {
  const target = join(SOURCES_DIR, source.label)
  const marker = join(target, '.sha256')
  const filesDir = join(target, source.dir)
  if (!force && existsSync(marker) && existsSync(filesDir)) return filesDir
  console.error(`fetch-corpus: downloading ${source.label} (${source.url})`)
  const response = await globalThis.fetch(source.url)
  if (!response.ok) fail(`${source.url} answered ${response.status}`)
  const bytes = Buffer.from(await response.arrayBuffer())
  const actual = createHash('sha256').update(bytes).digest('hex')
  if (actual !== source.sha256) fail(`${source.label}: SHA-256 is ${actual}, expected ${source.sha256}. Not unpacked.`)
  rmSync(target, { recursive: true, force: true })
  mkdirSync(target, { recursive: true })
  const archive = join(target, 'archive')
  writeFileSync(archive, bytes)
  // bsdtar (macOS, Windows 10+) and GNU tar (Linux) both read .tar.bz2.
  const untar = spawnSync('tar', ['-xf', archive, '-C', target], { stdio: 'inherit' })
  rmSync(archive, { force: true })
  if (untar.status !== 0) fail(`could not unpack ${source.label} with tar`)
  if (!existsSync(filesDir)) fail(`${source.label}: the archive has no ${source.dir}/ folder`)
  writeFileSync(marker, `${source.sha256}\n`)
  return filesDir
}

async function main() {
  const force = process.argv.includes('--force')
  const roots = []
  for (const source of SOURCES) {
    const dir = await fetchSource(source, force)
    roots.push({ label: source.label, dir: relative(ROOT, dir).split('\\').join('/'), licence: source.licence, url: source.url })
  }
  mkdirSync(SOURCES_DIR, { recursive: true })
  writeFileSync(join(SOURCES_DIR, 'roots.json'), `${JSON.stringify(roots, null, 2)}\n`)
  for (const root of roots) console.log(`${root.label} (${root.licence}): ${root.dir}`)
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main()
}
