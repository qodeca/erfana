/**
 * The real-file corpus round trip (spec 024 024-NFR-003, 024-AC-026).
 *
 * Four modes, by environment:
 * - `CORPUS_COLLECT=1` – builds the corpus from files on disk
 *   (`corpusSources.ts`) and freezes it: a copy of each file's bytes in the
 *   git-ignored `temp/corpus/cache/`, so edits made while the run goes on
 *   cannot reach it;
 * - `CORPUS_RUN=1` with `CORPUS_SHARD=k/n` – one shard: runs its share of the files
 *   ({@link shardIndices}) through Erfana's writer with the independent oracle
 *   (`corpusRunner.ts`), and leaves its result in `temp/corpus/shards/`;
 * - `CORPUS_MERGE=1` with `CORPUS_SHARDS=n` – merges the n results and
 *   writes `specs/spec-t3-024-unified-comments/verification/corpus-round-trip.md`
 *   and the manifest beside it, then runs the merge-time tests on it;
 * - neither (CI): the merge-time tests read the committed report.
 *
 * `npm run test:corpus` (vitest.corpus.config.ts) collects, runs n shard
 * projects in parallel, then the merge. It takes about an hour, so it is never part of
 * the default suite. `CORPUS_LIMIT=<n>` takes the first n files of each kind
 * and writes to `temp/corpus/` instead, for a trial.
 */
import { execFileSync } from 'node:child_process'
import { cpus, platform, release } from 'node:os'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import { decodeLossless } from '../../../../shared/comments/encoding'
import { loadMarkdownIt, markdownItVersion } from './__test-helpers__/corpusOracle'
import { kindSection, parseCorpusSummary, summaryBlock, totalsOf, type CorpusSummary } from './__test-helpers__/corpusReport'
import { CORPUS_AUTHOR, runCorpusFile, type FileOutcome } from './__test-helpers__/corpusRunner'
import { markdownSizeOf, sizeTable, type MarkdownSize } from './__test-helpers__/corpusSizes'
import { collectCorpus, extraRootsFromEnv, manifestText, sha256, snapshotCorpus, type CorpusEntry, type ExtraRoot } from './__test-helpers__/corpusSources'
import { TARGETS_PER_FILE } from './__test-helpers__/corpusTargets'

const ROOT = join(__dirname, '..', '..', '..', '..', '..')
const VERIFICATION = join(ROOT, 'specs', 'spec-t3-024-unified-comments', 'verification')
const REPORT = join(VERIFICATION, 'corpus-round-trip.md')
/** Each shard's result, for the merge (git-ignored). */
const SHARD_DIR = join(ROOT, 'temp', 'corpus', 'shards')
/** The frozen corpus: its entries, and a copy of each file's bytes by SHA-256 (git-ignored). */
const COLLECTION = join(ROOT, 'temp', 'corpus', 'collection.json')
const CACHE_DIR = join(ROOT, 'temp', 'corpus', 'cache')
/** The seed when `CORPUS_SEED` is unset: fixed, so a rerun on the same files repeats. */
const DEFAULT_SEED = 24_026
/** 024-NFR-003's floors. */
const MIN_MARKDOWN_FILES = 2_000
const MIN_HTML_FILES = 500
const MAX_REFUSED_SHARE = 0.02
/** Long enough for the whole corpus on a slow machine. */
const RUN_TIMEOUT_MS = 6 * 60 * 60 * 1000

function git(...args: string[]): string {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim()
}

function sizesOf(entries: readonly CorpusEntry[]): MarkdownSize[] {
  const out: MarkdownSize[] = []
  for (const entry of entries) {
    const decoded = decodeLossless(new Uint8Array(readFileSync(entry.absolute)))
    if (!decoded.ok) continue
    try {
      out.push(markdownSizeOf(decoded.text))
    } catch {
      // A file too deep for remark's parse is measured by the scanner alone (it is past a limit).
    }
  }
  return out
}

interface RunInfo {
  readonly seed: number
  readonly commit: string
  readonly dirty: boolean
  readonly manifestHash: string
  readonly skipped: { readonly notPermissive: number; readonly duplicate: number }
  readonly extras: string
  /** The command that repeats this run on the same machine. */
  readonly rerun: string
  readonly minutes: number
  readonly shards: number
}

function renderReport(info: RunInfo, md: readonly FileOutcome[], html: readonly FileOutcome[], sizes: readonly MarkdownSize[]): string {
  const summary: CorpusSummary = { seed: info.seed, commit: info.commit, date: new Date().toISOString().slice(0, 10), markdown: totalsOf(md), html: totalsOf(html) }
  const it = markdownItVersion(ROOT)
  return [
    '<!-- SPDX-License-Identifier: GPL-3.0-only -->',
    '<!-- SPDX-FileCopyrightText: 2025-2026 Qodeca sp. z o.o. -->',
    '',
    '# Corpus round trip (024-NFR-003, 024-AC-026)',
    '',
    'Generated by `npm run test:corpus` (`src/main/services/comments/corpus/corpusRoundTrip.test.ts`); do not edit by hand.',
    '',
    '## Run',
    '',
    `- Commit: \`${info.commit}\`${info.dirty ? ' plus uncommitted changes in the working tree' : ''}`,
    `- Seed: ${info.seed} (\`CORPUS_SEED\` replays it); up to ${TARGETS_PER_FILE} targets per file – the first, the last and up to 3 more covering the file's block kinds`,
    `- Actions per target: add, reply, edit, resolve, delete; delete must give back the original bytes`,
    `- Identity: ${CORPUS_AUTHOR.name} <${CORPUS_AUTHOR.email}> (made up, C20)`,
    `- Machine: ${platform()} ${release()}, ${cpus()[0]?.model ?? 'unknown CPU'} × ${cpus().length}, Node ${process.version}`,
    `- Duration: ${info.minutes.toFixed(1)} min wall time, ${info.shards} shards in parallel (one vitest project each)`,
    `- Writer: the parse worker's write jobs (\`runWriteJob\` with the Markdown or HTML kind) run in process, then main's \`isSafeInsert\` and \`assembleSplice\`; nothing written to disk`,
    `- Oracle: thread id text search for the permitted range; the preview pipeline (\`previewTree\`, line breaks off and on) and ${it === undefined ? 'no markdown-it (not installed)' : `markdown-it ${it}`} for Markdown; the parse5 DOM without comments for HTML; the frozen v0.23.1 parser`,
    '- cmark-gfm: **not run** – no cmark-gfm build is a dependency of the repository and none is installed on this machine; markdown-it (CommonMark) is the independent second render. Its differences are listed per kind and are not counted as failures',
    '',
    '## Corpus',
    '',
    'Built at run time from files already on disk (never fetched, never committed): the repository\'s tracked Markdown and HTML (test fixtures and this folder excluded), the installed packages under `node_modules` with a permissive licence (from each owning package\'s `package.json`), and the extra roots named in `CORPUS_EXTRA_ROOTS`. Identical bytes count once.',
    '',
    `- Extra roots: ${info.extras}`,
    `- Rerun: \`${info.rerun}\``,
    `- Left out: ${info.skipped.notPermissive} files without a permissive licence, ${info.skipped.duplicate} duplicates`,
    `- Manifest: [corpus-manifest.tsv](corpus-manifest.tsv) (source, path, kind, bytes, SHA-256, licence), SHA-256 \`${info.manifestHash}\``,
    '',
    ...kindSection('Markdown', 'markdown', md),
    ...kindSection('HTML', 'html', html),
    '## Markdown size data (C19)',
    '',
    ...sizeTable(sizes),
    '',
    '## Summary (machine-readable)',
    '',
    summaryBlock(summary),
    ''
  ].join('\n')
}

/** What one shard leaves for the merge. */
interface ShardResult {
  readonly shard: number
  readonly of: number
  readonly seed: number
  readonly manifestHash: string
  readonly startedAt: number
  readonly finishedAt: number
  /** The manifest positions of this shard's files, in run order. */
  readonly indices: number[]
  readonly outcomes: FileOutcome[]
  readonly sizes: MarkdownSize[]
}

/** `k/n` from `CORPUS_SHARD`; one shard of one when unset. */
function shardOf(value = process.env.CORPUS_SHARD): { readonly shard: number; readonly of: number } {
  const [shard, of] = (value ?? '0/1').split('/').map(Number)
  if (!Number.isInteger(shard) || !Number.isInteger(of) || shard < 0 || of < 1 || shard >= of) throw new Error(`CORPUS_SHARD must be k/n, got ${value}`)
  return { shard, of }
}

/** The frozen corpus of a run (`snapshotCorpus`), written by the collect step. */
interface CollectedCorpus {
  readonly entries: CorpusEntry[]
  readonly skippedNotPermissive: number
  readonly skippedDuplicate: number
  readonly extras: ExtraRoot[]
}

/** The corpus this run uses: the collect step's snapshot, the same in every shard and in the merge. */
function corpus(): CollectedCorpus & { readonly seed: number } {
  if (!existsSync(COLLECTION)) throw new Error('no collected corpus: run `npm run test:corpus`, which collects it first')
  const collected = JSON.parse(readFileSync(COLLECTION, 'utf8')) as CollectedCorpus
  const limit = process.env.CORPUS_LIMIT ? Number(process.env.CORPUS_LIMIT) : undefined
  const byKind = (kind: CorpusEntry['kind']): CorpusEntry[] => collected.entries.filter(e => e.kind === kind).slice(0, limit)
  const seed = process.env.CORPUS_SEED ? Number(process.env.CORPUS_SEED) : DEFAULT_SEED
  return { ...collected, entries: [...byKind('markdown'), ...byKind('html')], seed }
}

/**
 * Each shard's files, as manifest positions: largest first, each to the shard
 * with the fewest bytes so far, so one very large file does not hold back a
 * shard that also has its share of the rest.
 */
function shardIndices(entries: readonly CorpusEntry[], of: number): number[][] {
  const shards = Array.from({ length: of }, () => ({ bytes: 0, indices: [] as number[] }))
  const bySize = entries.map((_, i) => i).sort((a, b) => entries[b].bytes - entries[a].bytes || a - b)
  for (const i of bySize) {
    const lightest = shards.reduce((min, shard) => (shard.bytes < min.bytes ? shard : min))
    lightest.bytes += entries[i].bytes
    lightest.indices.push(i)
  }
  return shards.map(shard => shard.indices.sort((a, b) => a - b))
}

/** Where a limited trial writes: never over the committed report. */
const outputDir = (): string => (process.env.CORPUS_LIMIT ? join(ROOT, 'temp', 'corpus') : VERIFICATION)
const shardFile = (shard: number, of: number): string => join(SHARD_DIR, `shard-${shard}-of-${of}.json`)

describe.runIf(process.env.CORPUS_COLLECT === '1')('corpus round trip (collects the corpus)', () => {
  it('builds the corpus from files on disk and freezes it in the git-ignored cache', () => {
    const extras = extraRootsFromEnv()
    const frozen = snapshotCorpus(collectCorpus(ROOT, extras), CACHE_DIR)
    const collected: CollectedCorpus = { entries: [...frozen.entries], skippedNotPermissive: frozen.skippedNotPermissive, skippedDuplicate: frozen.skippedDuplicate, extras }
    mkdirSync(join(ROOT, 'temp', 'corpus'), { recursive: true })
    writeFileSync(COLLECTION, JSON.stringify(collected))
    console.info(`corpus: ${collected.entries.length} files collected`)
  })
})

describe.runIf(process.env.CORPUS_RUN === '1')('corpus round trip (one shard of the corpus)', () => {
  it(
    'runs its share of the corpus files through the writer',
    async () => {
      const startedAt = Date.now()
      const { shard, of } = shardOf()
      const { entries, seed } = corpus()
      const indices = shardIndices(entries, of)[shard]
      const mine = indices.map(i => entries[i])
      const md = loadMarkdownIt(ROOT)
      const outcomes: FileOutcome[] = []
      for (const [i, entry] of mine.entries()) {
        outcomes.push(await runCorpusFile(entry, seed, md))
        if ((i + 1) % 50 === 0) console.info(`corpus shard ${shard}/${of}: ${i + 1}/${mine.length} files`)
      }
      const result: ShardResult = {
        shard,
        of,
        seed,
        manifestHash: sha256(manifestText(entries)),
        startedAt,
        finishedAt: Date.now(),
        indices,
        outcomes,
        sizes: sizesOf(mine.filter(e => e.kind === 'markdown'))
      }
      mkdirSync(SHARD_DIR, { recursive: true })
      writeFileSync(shardFile(shard, of), JSON.stringify(result))
    },
    RUN_TIMEOUT_MS
  )
})

describe.runIf(process.env.CORPUS_MERGE === '1')('corpus round trip (merges the shards, writes the report)', () => {
  it('merges every shard and writes verification/corpus-round-trip.md', () => {
    const of = Number(process.env.CORPUS_SHARDS ?? '1')
    const { entries, skippedNotPermissive, skippedDuplicate, extras, seed } = corpus()
    const manifest = manifestText(entries)
    const shards = Array.from({ length: of }, (_, k) => {
      if (!existsSync(shardFile(k, of))) throw new Error(`shard ${k}/${of} left no result`)
      return JSON.parse(readFileSync(shardFile(k, of), 'utf8')) as ShardResult
    })
    for (const s of shards) {
      expect(s.manifestHash, `shard ${s.shard}`).toBe(sha256(manifest))
      expect(s.seed, `shard ${s.shard}`).toBe(seed)
    }
    // Back in manifest order.
    const outcomes: FileOutcome[] = new Array<FileOutcome>(entries.length)
    for (const s of shards) s.indices.forEach((index, at) => (outcomes[index] = s.outcomes[at]))
    expect(outcomes.filter(o => o !== undefined)).toHaveLength(entries.length)
    const minutes = (Math.max(...shards.map(s => s.finishedAt)) - Math.min(...shards.map(s => s.startedAt))) / 60_000
    const info: RunInfo = {
      seed,
      commit: git('rev-parse', 'HEAD'),
      dirty: git('status', '--porcelain') !== '',
      manifestHash: sha256(manifest),
      skipped: { notPermissive: skippedNotPermissive, duplicate: skippedDuplicate },
      extras: extras.length === 0 ? 'none' : extras.map(x => `${x.label} (${x.licence}, ${x.dir})`).join('; '),
      rerun: `${extras.length === 0 ? '' : `CORPUS_EXTRA_ROOTS='${JSON.stringify(extras)}' `}CORPUS_SEED=${seed} CORPUS_SHARDS=${of} npm run test:corpus`,
      minutes,
      shards: of
    }
    const report = renderReport(info, outcomes.filter(o => o.entry.kind === 'markdown'), outcomes.filter(o => o.entry.kind === 'html'), shards.flatMap(s => s.sizes))
    const dir = outputDir()
    mkdirSync(dir, { recursive: true })
    writeFileSync(join(dir, 'corpus-manifest.tsv'), manifest)
    writeFileSync(join(dir, 'corpus-round-trip.md'), report)
    console.info(`corpus: ${outcomes.length} files in ${minutes.toFixed(1)} min over ${of} shards – ${join(dir, 'corpus-round-trip.md')}`)
  })
})

describe.skipIf(process.env.CORPUS_COLLECT === '1' || process.env.CORPUS_RUN === '1' || process.env.CORPUS_LIMIT !== undefined)('024-AC-026 corpus round trip report (merge-time)', () => {
  const summary = (): CorpusSummary => {
    if (!existsSync(REPORT)) throw new Error('verification/corpus-round-trip.md is missing: run `npm run test:corpus`')
    return parseCorpusSummary(readFileSync(REPORT, 'utf8'))
  }

  it('024-AC-026 the report covers at least 2,000 Markdown and 500 HTML files, with its seed and commit', () => {
    const s = summary()
    expect(s.markdown.files).toBeGreaterThanOrEqual(MIN_MARKDOWN_FILES)
    expect(s.html.files).toBeGreaterThanOrEqual(MIN_HTML_FILES)
    expect(Number.isInteger(s.seed)).toBe(true)
    expect(s.commit).toMatch(/^[0-9a-f]{40}$/)
  })

  it('024-AC-026 no file changed outside the permitted range, delete gave back every file, and nothing failed', () => {
    const s = summary()
    for (const kind of [s.markdown, s.html]) {
      expect(kind.filesChangedOutsideRange).toBe(0)
      expect(kind.deleteNotIdentity).toBe(0)
      expect(kind.failed).toBe(0)
      expect(kind.saved + kind.refused).toBe(kind.targetsTried)
    }
  })

  it('024-AC-026 refused saves are at most 2 % of the targets tried', () => {
    const s = summary()
    const tried = s.markdown.targetsTried + s.html.targetsTried
    expect(tried).toBeGreaterThan(0)
    expect((s.markdown.refused + s.html.refused) / tried).toBeLessThanOrEqual(MAX_REFUSED_SHARE)
  })
})
