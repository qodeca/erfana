/**
 * Builds one React fixture app of the spec 025 browser tests into its
 * committed `bundle/` folder: a development bundle with linked source maps
 * (`bundle/dev/`, what "the React app" serves) and a minified production
 * bundle with no source maps (`bundle/prod/`, served under `/prod/`).
 *
 * Usage (from the repository root, Node 24 runs TypeScript directly):
 *   node e2e/fixtures/browser/apps/build-react-app.ts react18
 *   node e2e/fixtures/browser/apps/build-react-app.ts react19
 *
 * React is resolved from the app folder upwards, exactly as esbuild resolves
 * it, and the build refuses to run unless the installed `react` and
 * `react-dom` versions equal the exact pins in the app's package.json – so a
 * React 19 app can never be built against the repository's React 18.
 */

import { build, type BuildOptions } from 'esbuild'
import * as fs from 'node:fs'
import { createRequire } from 'node:module'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'

const APPS_DIR = path.dirname(fileURLToPath(import.meta.url))
const APPS = ['react18', 'react19'] as const
type AppName = (typeof APPS)[number]
const PINNED_PACKAGES = ['react', 'react-dom'] as const

// The bundles hold React itself (MIT) next to the fixture code. The banner
// is the bundle's own licence header; the markers keep `reuse lint` from
// reading the literal as this file's licence.
// REUSE-IgnoreStart
const GENERATED = 'Generated by e2e/fixtures/browser/apps/build-react-app.ts – rebuild, do not edit.'
const JS_LICENSE_LINES = [
  'SPDX-License-Identifier: GPL-3.0-only AND MIT',
  'SPDX-FileCopyrightText: 2025-2026 Qodeca sp. z o.o.',
  'SPDX-FileCopyrightText: Meta Platforms, Inc. and affiliates',
  GENERATED
]
// The stylesheet holds only the fixture's own CSS.
const CSS_LICENSE_LINES = [
  'SPDX-License-Identifier: GPL-3.0-only',
  'SPDX-FileCopyrightText: 2025-2026 Qodeca sp. z o.o.',
  GENERATED
]
// REUSE-IgnoreEnd
const BANNER = {
  js: JS_LICENSE_LINES.map((line) => `// ${line}`).join('\n'),
  css: CSS_LICENSE_LINES.map((line) => `/* ${line} */`).join('\n')
}

function isAppName(value: string | undefined): value is AppName {
  return APPS.some((app) => app === value)
}

function readJson<T>(file: string): T {
  return JSON.parse(fs.readFileSync(file, 'utf8')) as T
}

/** Throws unless the React packages esbuild will bundle are the exact pinned versions. */
function checkPinnedVersions(appDir: string): void {
  const manifest = readJson<{ dependencies: Record<string, string> }>(path.join(appDir, 'package.json'))
  const requireFromApp = createRequire(path.join(appDir, 'package.json'))
  for (const name of PINNED_PACKAGES) {
    const pinned = manifest.dependencies[name]
    let manifestPath: string
    try {
      manifestPath = requireFromApp.resolve(`${name}/package.json`)
    } catch {
      throw new Error(`${name} is not installed for ${appDir} – run "npm ci --prefix ${appDir}" first`)
    }
    const installed = readJson<{ version: string }>(manifestPath).version
    if (installed !== pinned) {
      throw new Error(
        `${name} ${installed} (from ${manifestPath}) does not match the pin ${pinned} – run "npm ci --prefix ${appDir}" first`
      )
    }
    console.log(`${name} ${installed} from ${path.relative(process.cwd(), manifestPath)}`)
  }
}

function buildOptions(appDir: string, mode: 'dev' | 'prod'): BuildOptions {
  const dev = mode === 'dev'
  return {
    absWorkingDir: appDir,
    entryPoints: { app: path.join(appDir, 'src', 'main.tsx') },
    outdir: path.join(appDir, 'bundle', mode),
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2022',
    charset: 'utf8',
    jsx: 'automatic',
    // jsxDEV calls carry file, line and column into React's development build.
    jsxDev: dev,
    define: { 'process.env.NODE_ENV': JSON.stringify(dev ? 'development' : 'production') },
    minify: !dev,
    sourcemap: dev ? 'linked' : false,
    sourcesContent: true,
    legalComments: 'eof',
    banner: BANNER,
    logLevel: 'warning'
  }
}

async function main(): Promise<void> {
  const app = process.argv[2]
  if (!isAppName(app)) {
    console.error(`Usage: node e2e/fixtures/browser/apps/build-react-app.ts <${APPS.join('|')}>`)
    process.exitCode = 2
    return
  }
  const appDir = path.join(APPS_DIR, app)
  checkPinnedVersions(appDir)
  for (const mode of ['dev', 'prod'] as const) {
    const options = buildOptions(appDir, mode)
    if (options.outdir) fs.rmSync(options.outdir, { recursive: true, force: true })
    await build(options)
    console.log(`built ${path.relative(process.cwd(), options.outdir ?? '')}`)
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error)
  process.exitCode = 1
})
